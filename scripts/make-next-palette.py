#!/usr/bin/env python3
"""Genereerib src/next/palette.css: uue liidese (Kodu-plaan) värvid klassikalise --tN paleti põhjal.
Hele teema: sooja paberi ja sinise tindi palett, teal muutub metsrohelisks.
Tume teema: joonestuse (blueprint) navy taust."""
import re, colorsys, pathlib
css = pathlib.Path('src/styles.css').read_text()
def block(sel):
    m = re.search(re.escape(sel) + r'\{([^}]*)\}', css)
    return dict(re.findall(r'--(t\d+):(#[0-9a-fA-F]{3,8})', m.group(1)))
light, dark = block(':root'), block('[data-theme="dark"]')
def parse(h):
    h = h.lstrip('#')
    if len(h) in (3, 4): h = ''.join(c*2 for c in h)
    return int(h[0:2],16)/255, int(h[2:4],16)/255, int(h[4:6],16)/255, h[6:8]
def fmt(r,g,b,a):
    return '#%02x%02x%02x%s' % (round(r*255), round(g*255), round(b*255), a)
def tr(hex_, mode):
    r,g,b,a = parse(hex_)
    h,l,s = colorsys.rgb_to_hls(r,g,b)
    hd = h*360
    chroma = max(r,g,b) - min(r,g,b)
    if chroma >= .12:
        if 168 <= hd <= 200:            # teal aktsent
            if mode == 'light': h, s, l = 150/360, min(s*.85, .6), l*.92 if l < .7 else l
            else: h = 188/360
        return fmt(*colorsys.hls_to_rgb(h, l, s), a)
    if not (hd >= 150 or hd <= 60) or hd < 150 and hd > 60: pass
    if mode == 'light':
        if l >= .985: h, s = 42/360, .6          # peaaegu valge -> soe valge
        elif l >= .85: h, s = 40/360, .55         # taust -> paber
        elif l >= .45: h, s = 34/360, .10         # keskmised toonid -> soe hall
        else: h, s = 213/360, min(max(s, .3), .5) # tume tekst -> sinine tint
    else:
        if l < .30: h, s = 214/360, .48
        elif l < .62: h, s = 212/360, .30
        else: h, s = 205/360, .28
    return fmt(*colorsys.hls_to_rgb(h, l, s), a)
def emit(sel, pal, mode, extra):
    body = ';'.join(f'--{k}:{tr(v, mode)}' for k, v in pal.items())
    return f'{sel}{{{body};{extra}}}\n'
out = '/* Generated by scripts/make-next-palette.py — ära muuda käsitsi. */\n'
out += emit('html[data-ui="next"]:root', light, 'light', '--ink:#1f3347;--muted:#6f6a5e;--teal:#2f6b4f;--line:#e2d8c4;--orange:#c4572d;--surface:#fffdf8;--canvas:#f4efe4;--nx-heat:#c4572d;--nx-water:#2b7fa8;--nx-ok:#5e8c61;--nx-paper:#f4efe4;--nx-ink:#1f3347;--nx-line:#cfc3a9')
out += emit('html[data-ui="next"][data-theme="dark"]', dark, 'dark', 'color-scheme:dark;--ink:#dce8f2;--muted:#8fa6ba;--teal:#5cc8d6;--line:#233a52;--orange:#f08a55;--surface:#12233a;--canvas:#0b1726;--nx-heat:#f08a55;--nx-water:#5cb8e6;--nx-ok:#6fd0a0;--nx-paper:#0b1726;--nx-ink:#dce8f2;--nx-line:#35516d')
pathlib.Path('src/next/palette.css').write_text(out)
print(len(out), 'bytes')
